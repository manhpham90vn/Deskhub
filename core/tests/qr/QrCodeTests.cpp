constexpr int kVersionOneSize = 21;
constexpr int kVersionTwoSize = 25;
constexpr int kVersionFortySize = 177;
constexpr size_t kVersionOneCapacityM = 14;
constexpr size_t kVersionFortyCapacityM = 2331;

int SizeOfVersion(int version) {
    return kVersionOneSize + (version - 1) * 4;
}

std::vector<std::string_view> SplitRows(std::string_view rows) {
    std::vector<std::string_view> result;
    while (!rows.empty()) {
        const size_t end = rows.find('\n');
        result.push_back(rows.substr(0, end));
        rows.remove_prefix(end == std::string_view::npos ? rows.size() : end + 1);
    }
    return result;
}

int MismatchedModules(const QrCode& code, std::string_view rows) {
    const auto lines = SplitRows(rows);
    if (int(lines.size()) != code.size) return code.size * code.size;
    int mismatches = 0;
    for (int y = 0; y < code.size; ++y) {
        if (int(lines[size_t(y)].size()) != code.size) return code.size * code.size;
        for (int x = 0; x < code.size; ++x) {
            const bool wantDark = lines[size_t(y)][size_t(x)] == '1';
            if (code.Dark(x, y) != wantDark) ++mismatches;
        }
    }
    return mismatches;
}

size_t CodePoints(std::string_view line) {
    size_t count = 0;
    for (const char c : line) {
        if ((uint8_t(c) & 0xC0) != 0x80) ++count;
    }
    return count;
}

void TestReferenceSymbols() {
    std::printf("[qr] known inputs reproduce the reference matrices module for module...\n");
    for (const ReferenceSymbol& ref : kReferenceSymbols) {
        const auto code = EncodeQr(ref.text);
        Check(code.has_value(), ref.label);
        if (!code) continue;
        Check(code->size == SizeOfVersion(ref.version), "the reference version is chosen");
        const int mismatches = MismatchedModules(*code, ref.rows);
        if (mismatches != 0) std::printf("  %s: %d modules differ from the reference\n", ref.label, mismatches);
        Check(mismatches == 0, "every module matches the independently generated reference");
    }
}

void TestVersionSelection() {
    std::printf("[qr] the smallest version that fits is chosen...\n");
    const std::string fits(kVersionOneCapacityM, 'x');
    const auto one = EncodeQr(fits);
    Check(one && one->size == kVersionOneSize, "14 bytes fit version 1-M");
    const auto two = EncodeQr(fits + "x");
    Check(two && two->size == kVersionTwoSize, "15 bytes need version 2-M");
    const std::string largest(kVersionFortyCapacityM, 'x');
    const auto forty = EncodeQr(largest);
    Check(forty && forty->size == kVersionFortySize, "2331 bytes fill version 40-M");
    Check(!EncodeQr(largest + "x").has_value(), "2332 bytes do not fit any version");
    Check(!EncodeQr("").has_value(), "empty input is rejected");
}

void TestModuleAccess() {
    std::printf("[qr] module lookups outside the symbol are light...\n");
    const auto code = EncodeQr("HELLO WORLD");
    Check(code.has_value(), "the sample encodes");
    if (!code) return;
    Check(code->modules.size() == size_t(code->size) * size_t(code->size), "one byte per module");
    Check(code->Dark(0, 0) && code->Dark(code->size - 1, 0) && code->Dark(0, code->size - 1),
        "the finder corners are dark");
    Check(!code->Dark(7, 7), "the separator is light");
    Check(!code->Dark(-1, 0) && !code->Dark(0, -1), "negative coordinates are light");
    Check(!code->Dark(code->size, 0) && !code->Dark(0, code->size), "coordinates past the edge are light");
    Check(!QrCode{}.Dark(0, 0), "an empty code has no dark module");
}

void TestTextRendering() {
    std::printf("[qr] the text rendering packs two module rows per line inside a quiet zone...\n");
    for (const ReferenceSymbol& ref : kReferenceSymbols) {
        const auto code = EncodeQr(ref.text);
        if (!code) continue;
        const std::string text = RenderQrText(*code);
        const auto lines = SplitRows(text);
        const int quietExtent = code->size + 2;
        Check(int(lines.size()) == (quietExtent + 1) / 2, "line count covers the symbol and quiet zone in half-blocks");
        Check(!text.empty() && text.back() == '\n', "every line ends with a newline");
        bool equalWidth = true;
        for (const std::string_view line : lines) equalWidth = equalWidth && CodePoints(line) == size_t(quietExtent);
        Check(equalWidth, "every line spans the same number of code points");
    }
    const auto sample = EncodeQr("HELLO WORLD");
    if (!sample) return;
    const std::string rendered = RenderQrText(*sample);
    const auto lines = SplitRows(rendered);
    std::string firstLine = " ";
    for (int i = 0; i < 7; ++i) firstLine += "\xE2\x96\x84";
    Check(lines.front().substr(0, firstLine.size()) == firstLine,
        "the quiet zone row is light and the finder row below it shows as lower half-blocks");
    Check(lines.back().substr(0, 1) == " ", "the quiet zone corner below the symbol is blank");
}

